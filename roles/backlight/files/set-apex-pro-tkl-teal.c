#include <hidapi-hotplug/hidapi.h>
#include <stdio.h>
#include <string.h>

#define STEELSERIES_VENDOR_ID 0x1038
#define APEX_PRO_TKL_PRODUCT_ID 0x1614
#define CONTROL_INTERFACE 1

static const unsigned char keys[] = {
    0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D,
    0x0E, 0x0F, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
    0x18, 0x19, 0x1A, 0x1B, 0x1C, 0x1D, 0x1E, 0x1F, 0x20, 0x21,
    0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x28, 0x29, 0x2A, 0x2B,
    0x2C, 0x2D, 0x2E, 0x2F, 0x30, 0x32, 0x33, 0x34, 0x35, 0x36,
    0x37, 0x38, 0x39, 0x3A, 0x3B, 0x3C, 0x3D, 0x3E, 0x3F, 0x40,
    0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47, 0x48, 0x49, 0x4A,
    0x4B, 0x4C, 0x4D, 0x4E, 0x4F, 0x50, 0x51, 0x52, 0x64, 0xE0,
    0xE1, 0xE2, 0xE3, 0xE4, 0xE5, 0xE6, 0xE7, 0xF0, 0x31, 0x87,
    0x88, 0x89, 0x8A, 0x8B, 0x53, 0x54, 0x55, 0x56, 0x57, 0x58,
    0x59, 0x5A, 0x5B, 0x5C, 0x5D, 0x5E, 0x5F, 0x60, 0x61, 0x62,
    0x63, 0xFB
};

int main(void) {
    struct hid_device_info *devices;
    struct hid_device_info *entry;
    hid_device *device = NULL;
    unsigned char report[643] = {0};

    devices = hid_enumerate(STEELSERIES_VENDOR_ID, APEX_PRO_TKL_PRODUCT_ID);
    for (entry = devices; entry; entry = entry->next) {
        if (entry->interface_number == CONTROL_INTERFACE) {
            device = hid_open_path(entry->path);
            break;
        }
    }

    if (!device) {
        fprintf(stderr, "SteelSeries Apex Pro TKL control interface not found\n");
        hid_free_enumeration(devices);
        return 1;
    }

    /* The keyboard responds to the legacy direct-color command, unlike the
       Gen3 command selected by OpenRGB 1.0. Set every known key to #008080. */
    report[1] = 0x3A;
    report[2] = sizeof(keys);
    for (unsigned int i = 0; i < sizeof(keys); i++) {
        report[(i * 4) + 3] = keys[i];
        report[(i * 4) + 4] = 0x00;
        report[(i * 4) + 5] = 0x80;
        report[(i * 4) + 6] = 0x80;
    }

    if (hid_send_feature_report(device, report, sizeof(report)) < 0) {
        fwprintf(stderr, L"Could not set Apex Pro TKL backlight: %ls\n",
                 hid_error(device));
        hid_close(device);
        hid_free_enumeration(devices);
        hid_exit();
        return 1;
    }

    hid_close(device);
    hid_free_enumeration(devices);
    hid_exit();
    return 0;
}
